/* ============================================================================
   bot-strategies.js
   Pluggable bot strategies for TrumpMaster simulations. Every strategy
   exposes the same two-method interface:
     bidEstimate(hand, trumpSuit)              -> integer bid in [2,13]
     choosePlay(hand, trick, trumpSuit, legal) -> one card FROM `legal`
   Strategies only ever pick from the legal set returned by
   RuleEngine.getLegalCards — they never touch legality, only preference.
   This keeps rule-engine.js completely untouched.
============================================================================ */

function clampBid(n){
  if(n<2) return 2;
  if(n>13) return 13;
  return n;
}

function groupBySuit(hand){
  const g = { S:[], H:[], D:[], C:[] };
  hand.forEach(c=>g[c.suit].push(c));
  return g;
}

// ---------------------------------------------------------------------------
// NAIVE — exactly what's shipped today (TrumpMaster_v0_2_Build03.html /
// simulate-match.js). Bids off raw card strength only (no hand shape).
// Plays the lowest legal card every time — never tries to win a trick it
// isn't forced to win by the legal-play hierarchy.
// ---------------------------------------------------------------------------
const naiveStrategy = {
  name: 'naive',
  bidEstimate(hand, trumpSuit){
    let est = 0;
    hand.forEach(c=>{
      if(c.suit===trumpSuit) est += 0.55;
      if(c.rank===14) est += 0.8; else if(c.rank===13) est += 0.55; else if(c.rank===12) est += 0.3;
    });
    return clampBid(Math.round(est));
  },
  choosePlay(hand, trick, trumpSuit, legalCards){
    return legalCards.slice().sort((a,b)=>a.rank-b.rank)[0];
  }
};

// ---------------------------------------------------------------------------
// HEURISTIC — "win cheaply if you can, duck if you can't."
//   Bid:   adds hand-shape awareness. A void or singleton in a non-trump
//          suit is worth extra when we're also holding trump, since it's a
//          future ruffing chance rather than a dead card.
//   Play:
//     - Leading: probe with the lowest card of our longest non-trump suit
//       (don't burn trump leading it). If the hand is all trump, lead the
//       lowest trump.
//     - Following, real choice: if any legal card currently beats the best
//       card on the trick, play the CHEAPEST such card — preferring a
//       non-trump winner over spending trump. If nothing beats the trick,
//       duck by discarding the lowest card from whichever suit we're
//       holding the fewest of overall (preserves long suits and trump).
// ---------------------------------------------------------------------------
function cardBeats(card, best, trumpSuit){
  if(!best) return true;
  if(card.suit===trumpSuit && best.suit!==trumpSuit) return true;
  if(card.suit!==trumpSuit && best.suit===trumpSuit) return false;
  if(card.suit===best.suit) return card.rank>best.rank;
  return false; // different non-trump suits can't beat one another
}

function currentTrickBest(trick, trumpSuit){
  if(!trick.length) return null;
  const trumped = trick.filter(p=>p.card.suit===trumpSuit);
  const pool = trumped.length ? trumped : trick.filter(p=>p.card.suit===trick[0].card.suit);
  return pool.reduce((a,b)=> b.card.rank>a.card.rank ? b : a).card;
}

// Coefficients fit by ordinary least squares (see collect-training-data.js +
// fit-regression.js) against 48,000 (hand -> tricks actually won) samples
// generated by playing out full matches with THIS strategy's own choosePlay
// on all four seats. R^2 = 0.591, mean |pred-actual| = 0.782 tricks.
// Bidding doesn't affect trick outcomes in this engine, so this cleanly
// isolates "what is this hand worth under heuristic play" from bidding
// itself. Re-run the two scripts above to refit if choosePlay ever changes.
const BID_COEFFICIENTS = {
  bias: -0.3030,
  trumpCount: 0.6768,
  aceCount: 0.5363,
  kingCount: 0.4117,
  queenCount: 0.2835,
  voidCount: 0.5856,
  singletonCount: 0.4102
};

const heuristicStrategy = {
  name: 'heuristic',
  bidEstimate(hand, trumpSuit){
    const bySuit = groupBySuit(hand);
    const trumpCount = bySuit[trumpSuit].length;
    let aceCount=0, kingCount=0, queenCount=0;
    hand.forEach(c=>{
      if(c.rank===14) aceCount++; else if(c.rank===13) kingCount++; else if(c.rank===12) queenCount++;
    });
    let voidCount=0, singletonCount=0;
    ['S','H','D','C'].forEach(s=>{
      if(s===trumpSuit) return;
      if(bySuit[s].length===0) voidCount++;
      else if(bySuit[s].length===1) singletonCount++;
    });
    const c = BID_COEFFICIENTS;
    const est = c.bias + c.trumpCount*trumpCount + c.aceCount*aceCount + c.kingCount*kingCount
      + c.queenCount*queenCount + c.voidCount*voidCount + c.singletonCount*singletonCount;
    return clampBid(Math.round(est));
  },
  choosePlay(hand, trick, trumpSuit, legalCards){
    if(!trick.length){
      const sideSuits = groupBySuit(hand.filter(c=>c.suit!==trumpSuit));
      let leadSuit = null, best = 0;
      ['S','H','D','C'].forEach(s=>{
        if(s===trumpSuit) return;
        if(sideSuits[s].length>best){ best=sideSuits[s].length; leadSuit=s; }
      });
      const pool = leadSuit ? legalCards.filter(c=>c.suit===leadSuit) : legalCards;
      return pool.slice().sort((a,b)=>a.rank-b.rank)[0];
    }

    const best = currentTrickBest(trick, trumpSuit);
    const winners = legalCards.filter(c=>cardBeats(c, best, trumpSuit));
    if(winners.length){
      const nonTrumpWinners = winners.filter(c=>c.suit!==trumpSuit);
      const pool = nonTrumpWinners.length ? nonTrumpWinners : winners;
      return pool.slice().sort((a,b)=>a.rank-b.rank)[0];
    }

    // Duck: discard from whichever suit (among what's actually legal right
    // now) we hold the fewest cards of overall.
    const bySuit = groupBySuit(hand);
    const bySuitInLegal = {};
    legalCards.forEach(c=>{ (bySuitInLegal[c.suit] ||= []).push(c); });
    const suits = Object.keys(bySuitInLegal);
    let worstSuit = suits[0], worstLen = Infinity;
    suits.forEach(s=>{
      if(bySuit[s].length<worstLen){ worstLen=bySuit[s].length; worstSuit=s; }
    });
    return bySuitInLegal[worstSuit].slice().sort((a,b)=>a.rank-b.rank)[0];
  }
};

// ---------------------------------------------------------------------------
// HARD — same tactical play as heuristicStrategy, but a bidder trained with
// reinforcement learning (REINFORCE / policy gradient, see
// train-rl-bidder.js) instead of regression. The OLS bidder above predicts
// E[tricks won] and rounds it — a good proxy, but not what the scoring rule
// actually rewards, since calculateDealScore punishes underbids much harder
// than equal-sized overbids and gives a bonus for landing exactly on bid.
// The RL bidder was trained directly against that real, asymmetric reward
// over ~3000 self-play matches (warm-started from the OLS weights, then
// checkpointed at its best-performing training chunk — see the learning
// curve printed by train-rl-bidder.js). Re-run that script to retrain if
// choosePlay or the scoring rule ever changes.
// ---------------------------------------------------------------------------
const RL_BID_COEFFICIENTS = {
  bias: -1.7898,
  trumpCount: 0.8659,
  aceCount: 0.5698,
  kingCount: 0.2946,
  queenCount: -0.0920,
  voidCount: 0.6258,
  singletonCount: 0.5851
};

const hardStrategy = {
  name: 'hard',
  bidEstimate(hand, trumpSuit){
    const bySuit = groupBySuit(hand);
    const trumpCount = bySuit[trumpSuit].length;
    let aceCount=0, kingCount=0, queenCount=0;
    hand.forEach(c=>{
      if(c.rank===14) aceCount++; else if(c.rank===13) kingCount++; else if(c.rank===12) queenCount++;
    });
    let voidCount=0, singletonCount=0;
    ['S','H','D','C'].forEach(s=>{
      if(s===trumpSuit) return;
      if(bySuit[s].length===0) voidCount++;
      else if(bySuit[s].length===1) singletonCount++;
    });
    const c = RL_BID_COEFFICIENTS;
    const est = c.bias + c.trumpCount*trumpCount + c.aceCount*aceCount + c.kingCount*kingCount
      + c.queenCount*queenCount + c.voidCount*voidCount + c.singletonCount*singletonCount;
    return clampBid(Math.round(est));
  },
  choosePlay: heuristicStrategy.choosePlay
};

// ---------------------------------------------------------------------------
// Difficulty-tier aliases. "easy" is the shipped naive bot as-is (weak bid
// formula AND lowest-card play — both axes worse). "medium" is the
// regression-calibrated heuristic bidder + smarter play. "hard" swaps in the
// RL-trained bidder on top of the same play as medium. Keeping naiveStrategy
// / heuristicStrategy exported too so nothing else that imports them by
// their original names breaks.
// ---------------------------------------------------------------------------
const easyStrategy = { ...naiveStrategy, name: 'easy' };
const mediumStrategy = { ...heuristicStrategy, name: 'medium' };

module.exports = {
  naiveStrategy, heuristicStrategy, hardStrategy,
  easyStrategy, mediumStrategy,
  cardBeats, currentTrickBest
};
